!///////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////////
!
!  -----------------------------------------------------------------------------------------------------------------------
!  Subroutine to construct individual mesh partitions from an HDF5 mesh file
!  -----------------------------------------------------------------------------------------------------------------------
subroutine ConstructMeshPartition_FromHDF5File_( self, fileName, nodes, Nx, Ny, Nz, MeshInnerCurves, dir2D, periodRelative, success )
      implicit none
      !-arguments--------------------------------------------------------------
      class(HexMesh)  , intent(inout) :: self
      character(LEN=*), intent(in)    :: fileName
      integer         , intent(in)    :: nodes
      integer         , intent(in)    :: Nx(:), Ny(:), Nz(:)     !<  Polynomial orders for all the elements
      logical         , intent(in)    :: MeshInnerCurves
      integer         , intent(in)    :: dir2D
      logical                         :: periodRelative
      logical         , intent(out)   :: success
      !-local-variables---------------------------------------------------------
#ifdef HAS_HDF5
      ! Variables as called by Kopriva
      integer  :: numberOfAllElements
      integer  :: bFaceOrder        ! Polynomial order for aproximating curved faces
      integer  :: numBFacePoints    ! Number of points for describing a curved mesh
      integer  :: numberOfFaces
      integer                          :: nodeIDs(NODES_PER_ELEMENT), nodeMap(NODES_PER_FACE)
      character(LEN=BC_STRING_LENGTH)  :: names(FACES_PER_ELEMENT)
      CHARACTER(LEN=BC_STRING_LENGTH), pointer :: zoneNames(:)
      real(KIND=RP)                    :: corners(NDIM,NODES_PER_ELEMENT) ! Corners of element
      real(kind=RP), dimension(:)    , allocatable :: uNodes, vNodes
      real(kind=RP), dimension(:,:,:), allocatable :: values
      real(kind=RP)                    :: x(NDIM)
      real(KIND=RP)  , dimension(2)     :: uNodesFlat = [-1.0_RP,1.0_RP]
      real(KIND=RP)  , dimension(2)     :: vNodesFlat = [-1.0_RP,1.0_RP]
      real(KIND=RP)  , dimension(3,2,2) :: valuesFlat
      
      ! Variables as called in HOPR: For a description, see HOPR documentation
      integer                          :: nSides, nNodes, nUniqueSides
      integer         , allocatable    :: GlobalNodeIDs(:)
      double precision, allocatable    :: TempArray(:,:) !(kind=RP)
      real(kind=RP)   , allocatable    :: NodeCoords(:,:)
      integer         , allocatable    :: ElemInfo(:,:)
      integer         , allocatable    :: SideInfo(:,:)
      integer                          :: offset
      integer                          :: first, last
      INTEGER(HSIZE_T),POINTER         :: HSize(:)
      integer                          :: nBCs
      integer                          :: nDims
      CHARACTER(LEN=255), ALLOCATABLE  :: BCNames(:)
      
      ! Auxiliary variables
      integer, allocatable            :: gHOPR2pHORSESNodeMap(:)
      integer, allocatable            :: globalToLocalElementID(:)
      integer :: i,j,k,l, eID, GlobeID
      integer                    :: HOPRNodeID
      integer                    :: HCornerMap(8)
      integer                    :: HSideMap(6)
      integer                    :: HSideMap2(6)
      integer, allocatable       :: HNodeSideMap(:,:,:)
      logical                    :: CurveCondition

      ! Mortar connectivity table: (1)=local eID, (2)=face type, (3)=neighbour eID, (4:7)=slave eIDs
      integer, allocatable       :: HorsesMortars(:,:)
      integer                    :: sideInfoOffset        ! offset within SideInfo for current face (+4 for big mortar, +2 for small mortar)
      integer                    :: sideInfoOffset_m
      logical                    :: isConformingMesh
      ! Mesh topology counters
      integer :: nMasterMortars    ! number of non-conforming master faces (big mortar)
      integer :: nUniqueFaces      ! total number of unique faces (used to allocate self%faces)
      integer :: nSlaveEntries     ! number of non-conforming slave entries (4 per master)
      integer :: nSlaveFaces       ! number of non-conforming slave faces (small mortar)
      integer :: ll                ! loop index over the 4 slave faces of a master mortar
      integer :: masterElemGlobalID   ! global element ID of the master element (slave face lookup)
      integer :: masterFaceCGNS       ! CGNS face index of the master face being searched
      integer :: masterFaceHORSES     ! HORSES3D face index of the master face (after HSideMap2)
      logical :: masterFaceFound      ! .TRUE. once the master face is found during slave lookup
      integer :: sideInfoIdx          ! loop index over SideInfo entries of the master element
      integer :: slaveIdx             ! loop index over the 4 slave entries of a master side

      integer :: cgns_to_horses(4)    ! Permutation: CGNS mortar slave order -> HORSES3D slave order
      integer :: ll_src               ! Source index after applying cgns_to_horses

      !---------------------------------------------------------------
      
!
!     Initializations
!     ------------------------------------
      success         = .TRUE.
      self % nodeType = nodes
      
!
!     Prepare to read file
!     ------------------------------------
      call h5open_f(iError)
      call h5fopen_f (trim(filename), H5F_ACC_RDONLY_F, file_id, iError)
        
!
!     Read important mesh attributes
!     ------------------------------
      CALL GetHDF5Attribute(File_ID,'nElems',1,IntegerScalar=numberOfAllElements)
      CALL GetHDF5Attribute(File_ID,'Ngeo',1,IntegerScalar=bFaceOrder)
      CALL GetHDF5Attribute(File_ID,'nSides',1,IntegerScalar=nSides)
      CALL GetHDF5Attribute(File_ID,'nNodes',1,IntegerScalar=nNodes)
      CALL GetHDF5Attribute(File_ID,'nUniqueSides',1,IntegerScalar=nUniqueSides)
      
      allocate(ElemInfo(6,1:numberOfAllElements))
      call ReadArrayFromHDF5(File_ID,'ElemInfo',2,(/6,numberOfAllElements/),0,IntegerArray=ElemInfo)
      
      offset=ElemInfo(ELEM_FirstNodeInd,1)
      first=offset+1
      last =offset+nNodes
      
      ALLOCATE( GlobalNodeIDs(first:last) )
      CALL ReadArrayFromHDF5(File_ID,'GlobalNodeIDs',1,(/nNodes/),offset,IntegerArray=GlobalNodeIDs)
      
      allocate( NodeCoords(1:3,first:last),TempArray(1:3,first:last) )
      CALL ReadArrayFromHDF5(File_ID,'NodeCoords',2,(/3,nNodes/),offset,RealArray=TempArray)
      NodeCoords = TempArray
      deallocate (TempArray)
      
      offset=ElemInfo(ELEM_FirstSideInd,1)
      first=offset+1
      last =offset+nSides
      ALLOCATE(SideInfo(5,first:last))
      CALL ReadArrayFromHDF5(File_ID,'SideInfo',2,(/5,nSides/),offset,IntegerArray=SideInfo)
      
      CALL GetHDF5DataSize(File_ID,'BCNames',nDims,HSize)
      nBCs=INT(HSize(1),4)
      DEALLOCATE(HSize)
      ALLOCATE(BCNames(nBCs))
      CALL ReadArrayFromHDF5(File_ID,'BCNames',1,(/nBCs/),Offset,StrArray=BCNames)
      
!      
!     Set up for face patches
!     ---------------------------------------
      numBFacePoints = bFaceOrder + 1
      allocate(uNodes(numBFacePoints))
      allocate(vNodes(numBFacePoints))
      allocate(values(3,numBFacePoints,numBFacePoints))
      
      do i = 1, numBFacePoints
         uNodes(i) = -1._RP + (i-1) * (2._RP/bFaceOrder)
         vNodes(i) = uNodes(i)
      end do
      
!      
!     Some other initializations
!     ---------------------------------------
      HSideMap  = HOPR2HORSESSideMap()
      HSideMap2 = HOPR2HORSESSideMap2()
      HCornerMap = HOPR2HORSESCornerMap(bFaceOrder)
      call HOPR2HORSESNodeSideMap(bFaceOrder,HNodeSideMap)
      
!
!     Allocate memory
!     ---------------
      allocate( self % elements   (mpi_partition % no_of_elements) )
      allocate( self % nodes      (mpi_partition % no_of_nodes)    )
      allocate( self % HOPRnodeIDs(mpi_partition % no_of_nodes)    )
      allocate( globalToLocalElementID(numberOfAllElements) )
      self % no_of_elements    = mpi_partition % no_of_elements
      self % no_of_allElements = numberOfAllElements
      
      globalToLocalElementID   = -1
      self % HOPRnodeIDs       = mpi_partition % HOPRnodeIDs
      
      allocate ( self % Nx(self % no_of_elements) , self % Ny(self % no_of_elements) , self % Nz(self % no_of_elements) )

!
!     Detect whether the mesh has non-conforming interfaces
!     ------------------------------------------------------
      isConformingMesh = .TRUE. 
      do l = 1, nSides
         if (SideInfo(3,l)==-1 .OR. SideInfo(3,l)==-2 .OR. SideInfo(3,l)==-3) then 
            isConformingMesh = .FALSE. 
            exit 
         end if 
      end do 

      if (.NOT.isConformingMesh) then  
         nMasterMortars  = 0
         nSlaveEntries   = 0
         nSlaveFaces     = 0
         nUniqueFaces    = 0
         allocate(HorsesMortars(6, 6*mpi_partition % no_of_elements))
         HorsesMortars = 0
      end if 

!
!     Create HOPR node map
!     --------------------
      allocate ( gHOPR2pHORSESNodeMap (maxval(mpi_partition % HOPRnodeIDs)) )
      gHOPR2pHORSESNodeMap = -1
      do j = 1, mpi_partition % no_of_nodes
         gHOPR2pHORSESNodeMap(mpi_partition % HOPRnodeIDs(j)) = j
      end do
      
!
!     Construct the zoneNameDictionary
!     ------------------------------------------------------------------------
      do l = 1, NumberOfAllElements
         sideInfoOffset = 0
         do k = 1, FACES_PER_ELEMENT
            j = SideInfo(5,ElemInfo(3,l) + k + sideInfoOffset)
            if (j == 0) then
               names(HsideMap2(k)) = emptyBCName
            else
               names(HsideMap2(k)) = trim(BCNames(j))
            end if
            if (SideInfo(3,ElemInfo(3,l) + k + sideInfoOffset)==-1)  sideInfoOffset = sideInfoOffset + 4
            if (SideInfo(3,ElemInfo(3,l) + k + sideInfoOffset)==-2 .OR. &
                SideInfo(3,ElemInfo(3,l) + k + sideInfoOffset)==-3)  sideInfoOffset = sideInfoOffset + 2
         end do
         
         do k = 1, 6
            IF(TRIM(names(k)) /= emptyBCName) then
               call toLower( names(k) )
               zoneNames => zoneNameDictionary % allKeys()
               if ( all(trim(names(k)) .ne. zoneNames) ) then
                  call zoneNameDictionary % addValueForKey(trim(names(k)), trim(names(k)))
               end if
               deallocate (zoneNames)
            end if
         end do
      end do
      
!      
!     Construct the elements (partition only)
!     ---------------------------------------
      do eID = 1, self % no_of_elements
         
         GlobeID = mpi_partition % elementIDs(eID)
         
         DO k = 1, NODES_PER_ELEMENT
            HOPRNodeID  = ElemInfo(ELEM_FirstNodeInd,GlobeID) + HCornerMap(k)
            nodeIDs(k)  = gHOPR2pHORSESNodeMap(GlobalNodeIDs(HOPRNodeID))
            if (self % nodes(nodeIDs(k)) % GlobID < 0) then
               x = NodeCoords(:,HOPRNodeID) / Lref
               CALL ConstructNode( self % nodes(nodeIDs(k)), x, mpi_partition % nodeIDs(nodeIDs(k)) )
            end if
         END DO

         sideInfoOffset = 0
         do k = 1, FACES_PER_ELEMENT
            j = SideInfo(5,ElemInfo(3,GlobeID) + k + sideInfoOffset)
            if (j == 0) then
               names(HsideMap2(k)) = emptyBCName
            else
               names(HsideMap2(k)) = trim(BCNames(j))
            end if
            if (SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset)==-1)  sideInfoOffset = sideInfoOffset + 4
            if (SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset)==-2 .OR. &
                SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset)==-3)  sideInfoOffset = sideInfoOffset + 2
         end do
         
         if (MeshInnerCurves) then
            CurveCondition = (bFaceOrder == 1)
         else
            CurveCondition = all(names == emptyBCName)
         end if
         
         if (CurveCondition) then
            DO k = 1, NODES_PER_ELEMENT
               corners(:,k) = self % nodes(nodeIDs(k)) % x
            END DO
            self % elements(eID) % SurfInfo % IsHex8    = .TRUE.
            self % elements(eID) % SurfInfo % corners   = corners
         else
            DO k = 1, FACES_PER_ELEMENT 
               IF ( names(k) == emptyBCName .and. (.not. MeshInnerCurves) ) THEN
                  DO j = 1, NODES_PER_ELEMENT
                     corners(:,j) = self % nodes(nodeIDs(j)) % x
                  END DO
                  nodeMap           = localFaceNode(:,k)
                  valuesFlat(:,1,1) = corners(:,nodeMap(1))
                  valuesFlat(:,2,1) = corners(:,nodeMap(2))
                  valuesFlat(:,2,2) = corners(:,nodeMap(3))
                  valuesFlat(:,1,2) = corners(:,nodeMap(4))
                  call self % elements(eID) % SurfInfo % facePatches(k) % construct(uNodesFlat, vNodesFlat, valuesFlat)
               ELSE
                  DO j = 1, numBFacePoints
                     DO i = 1, numBFacePoints
                        HOPRNodeID = ElemInfo(ELEM_FirstNodeInd,GlobeID) + HNodeSideMap(i,j,k)
                        values(:,i,j) = NodeCoords(:,HOPRNodeID) / Lref
                     END DO  
                  END DO
                  call self % elements(eID) % SurfInfo % facePatches(k) % construct(uNodes, vNodes, values)
               END IF
            END DO
         end if
         
         call self % elements(eID) % Construct (Nx(GlobeID), Ny(GlobeID), Nz(GlobeID), nodeIDs, eID, GlobeID) 
         self % Nx(eID) = Nx(GlobeID)
         self % Ny(eID) = Ny(GlobeID)
         self % Nz(eID) = Nz(GlobeID)
         
         CALL SetElementBoundaryNames( self % elements(eID), names )
         
         globalToLocalElementID(GlobeID) = eID

      end do      ! eID = 1, self % no_of_elements

!
!     Build mortar connectivity table
!     --------------------------------
      nUniqueFaces = 0
      if (.not.isConformingMesh) then 
         do l = 1, self % no_of_elements
            k              = 1
            sideInfoOffset = 0
            GlobeID = mpi_partition % elementIDs(l)

            do while (k .LE. FACES_PER_ELEMENT)

               HorsesMortars(1,(l*6)-5 + HsideMap2(k) -1) = l
               HorsesMortars(2,(l*6)-5 + HsideMap2(k) -1) = 0

               ! Conforming interior face
               if ((SideInfo(2,ElemInfo(3,GlobeID)+k+sideInfoOffset) .GT.0) .AND. &
                   (SideInfo(3,ElemInfo(3,GlobeID)+k+sideInfoOffset) .GT.0)) then 
                  nUniqueFaces   = nUniqueFaces   + 1
                  HorsesMortars(3,(l*6)-5 + HsideMap2(k) -1) = SideInfo(3,ElemInfo(3,GlobeID)+k+sideInfoOffset)
               end if 

               ! Interior face registered by the neighbour (negative SideInfo(2))
               if ((SideInfo(2,ElemInfo(3,GlobeID)+k+sideInfoOffset) .LT.0) .AND. &
                   (SideInfo(3,ElemInfo(3,GlobeID)+k+sideInfoOffset) .GT.0)        .AND. &
                   (SideInfo(1,ElemInfo(3,GlobeID)+k+sideInfoOffset) .GT.0)) then 
                  HorsesMortars(3,(l*6)-5 + HsideMap2(k) -1) = -SideInfo(3,ElemInfo(3,GlobeID)+k+sideInfoOffset)
                  IF(globalToLocalElementID(SideInfo(3,ElemInfo(3,GlobeID)+k+sideInfoOffset))==-1) nUniqueFaces=nUniqueFaces+1
               end if 

               ! Boundary face
               if (SideInfo(5,ElemInfo(3,GlobeID)+k+sideInfoOffset) .NE. 0) then 
                  nUniqueFaces   = nUniqueFaces   + 1
                  HorsesMortars(2,(l*6)-5 + HsideMap2(k) -1) = -1
               end if 

               ! Non-conforming master (big mortar)
               if (SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset) == -1) then

                  HorsesMortars(2,(l*6)-5 + HsideMap2(k)-1) = 1
                  nMasterMortars = nMasterMortars + 1
                  nUniqueFaces   = nUniqueFaces   + 1

                  ! Select permutation: CGNS mortar slave order -> HORSES3D slave order
                  select case (HsideMap2(k))
                     case (2)       
                        cgns_to_horses = [2, 1, 4, 3]
                     case (6)       
                        cgns_to_horses = [1, 3, 2, 4]
                     case (3)       
                        cgns_to_horses = [1, 3, 2, 4]
                     case default   
                        cgns_to_horses = [1, 2, 3, 4]
                  end select

                  do ll = 1, 4
                     ll_src = cgns_to_horses(ll)
                     HorsesMortars(2+ll, (l*6)-5 + HsideMap2(k)-1) = SideInfo(3, ElemInfo(3,GlobeID) + k + sideInfoOffset + ll_src)
                     nSlaveEntries = nSlaveEntries + 1
                  end do

                  sideInfoOffset = sideInfoOffset + 4
                  self % elements(l) % MortarFaces(HsideMap2(k)) = 1    ! Big Mortar

               end if 

               ! Non-conforming slave (small mortar)
               if (SideInfo(1,ElemInfo(3,GlobeID) + k + sideInfoOffset) .LT. 0) then 
                  nSlaveFaces  = nSlaveFaces  + 1
                  nUniqueFaces = nUniqueFaces + 1
                  HorsesMortars(2,(l*6)-5 + HsideMap2(k) -1) = 2
                  HorsesMortars(3,(l*6)-5 + HsideMap2(k) -1) = SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset)

                  masterElemGlobalID = SideInfo(3,ElemInfo(3,GlobeID) + k + sideInfoOffset)
                  first = ElemInfo(3,masterElemGlobalID) + 1
                  last  = ElemInfo(4,masterElemGlobalID) 

                  masterFaceFound = .false.
                  masterFaceCGNS  = 1
                  sideInfoOffset_m = 0

                  do while (masterFaceCGNS .LE. FACES_PER_ELEMENT)
                     sideInfoIdx = ElemInfo(3,masterElemGlobalID) + masterFaceCGNS + sideInfoOffset_m

                     if (SideInfo(3,sideInfoIdx) == -1) then
                        do slaveIdx = 1, 4
                           if (SideInfo(2,sideInfoIdx+slaveIdx) == -SideInfo(2,ElemInfo(3,GlobeID)+k+sideInfoOffset)) then
                              masterFaceFound  = .true.
                              masterFaceHORSES = HSideMap2(masterFaceCGNS)

                              select case (masterFaceHORSES)
                              case (2)
                                 cgns_to_horses = [2, 1, 4, 3]
                              case (6)
                                 cgns_to_horses = [1, 3, 2, 4]
                              case (3)
                                 cgns_to_horses = [1, 3, 2, 4]
                              case default
                                 cgns_to_horses = [1, 2, 3, 4]
                              end select

                              do ll = 1, 4
                                 if (cgns_to_horses(ll) == slaveIdx) then
                                    self % elements(l) % MortarFaces(HsideMap2(k)) = ll
                                 end if
                              end do
                              exit
                           end if
                        end do
                        sideInfoOffset_m = sideInfoOffset_m + 4
                     else if (SideInfo(3,sideInfoIdx) == -2 .OR. SideInfo(3,sideInfoIdx) == -3) then
                        sideInfoOffset_m = sideInfoOffset_m + 2
                     end if

                     if (masterFaceFound) exit
                     masterFaceCGNS = masterFaceCGNS + 1
                  end do

                  self % elements(l) % MortarFaces(HsideMap2(k)) = 20 + self % elements(l) % MortarFaces(HsideMap2(k))
               end if 

               k = k + 1
            end do 
         end do 
      end if 

!
!     Construct the element faces
!     ---------------------------
      if (isConformingMesh) then 
         numberOfFaces        = GetOriginalNumberOfFaces(self)
         self % numberOfFaces = numberOfFaces
         ALLOCATE( self % faces(self % numberOfFaces) )
         CALL ConstructFaces( self, success )
      else 
         numberOfFaces        = nUniqueSides
         self % numberOfFaces = nUniqueFaces
         ALLOCATE( self % faces(nUniqueFaces) )
         self % nonconforming = .TRUE.
         CALL ConstructFaces( self, success, numberOfAllElements, HorsesMortars, globalToLocalElementID)    
      end if 

!
!     Get actual mesh element face IDs
!     --------------------------------
      CALL getElementsFaceIDs(self)

!
!     Cast MPI faces
!     --------------
      call ConstructMPIFaces( self % MPIfaces )
      call self % UpdateFacesWithPartition(mpi_partition, &
                                           numberOfAllElements, &
                                           globalToLocalElementID)

!
!     Build the different zones
!     -------------------------
      call self % ConstructZones()

!
!     Construct periodic faces
!     ---------------------------
      if (isConformingMesh) then 
         CALL ConstructPeriodicFaces( self, periodRelative )
         CALL DeletePeriodicMinusFaces( self )
      end if

!
!     Assign faces ID to elements
!     ---------------------------
      CALL getElementsFaceIDs(self)

!
!     Define boundary faces 
!     --------------------- 
      call self % DefineAsBoundaryFaces() 

!
!     Check if this is a 2D extruded mesh
!     -----------------------------------
      call self % CheckIfMeshIs2D()

!
!     Set the mesh as 2D if requested
!     -------------------------------
      if ( dir2D .ne. 0 ) then
         call SetMappingsToCrossProduct
         call self % CorrectOrderFor2DMesh(dir2D)
      end if

!
!     Set the element connectivities
!     ------------------------------
      call self % SetConnectivitiesAndLinkFaces(nodes)

!
!     Construct elements' and faces' geometry
!     ---------------------------------------
      call self % ConstructGeometry()

!
!     Finish up
!     ---------
      deallocate (ElemInfo)
      deallocate (SideInfo)
      deallocate (BCNames)
      deallocate (HNodeSideMap)
      deallocate (NodeCoords)
      deallocate (GlobalNodeIDs)
      deallocate (gHOPR2pHORSESNodeMap)
      deallocate (globalToLocalElementID)
      deallocate (uNodes, vNodes, values)
      
      if (.not. self % child) then
         CALL self % Describe         ( trim(fileName), bFaceOrder )
         CALL self % DescribePartition( )
      end if

!
!     Prepare mesh for I/O
!     --------------------
      call self % PrepareForIO

      self % numBFacePoints=numBFacePoints 

#else
      error stop ':: HDF5 is not linked correctly'
#endif

   end subroutine ConstructMeshPartition_FromHDF5File_

